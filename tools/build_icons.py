#!/usr/bin/env python3
"""Build analyzer/css/icons.css from the SVG sources in tools/icons/.

    python tools/build_icons.py           # rewrite icons.css
    python tools/build_icons.py --check   # fail if icons.css is out of date (CI-safe)

Each tools/icons/<name>.svg becomes a `.k-icon--<name>` class. The SVG is used as
a CSS mask, so the icon takes the text colour (currentColor) of where it sits and
needs no extra files at runtime (the page CSP allows data: images).
Draw new icons on a 24x24 grid with a 2px round stroke, like the existing ones.
"""
from __future__ import annotations

import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "icons"
OUT = ROOT / "analyzer" / "css" / "icons.css"

HEADER = """/* GENERATED by tools/build_icons.py from tools/icons/*.svg. Do not edit by hand.

   SVG icon set. Usage: <i class="k-icon k-icon--gear" aria-hidden="true"></i>,
   or KestrelIcon('gear') from js/icons.js. The icon is 1em square and drawn in
   the current text colour, so it follows font-size and color like a glyph. */
.k-icon {
  display: inline-block;
  flex: none;
  width: 1em;
  height: 1em;
  vertical-align: -0.125em;
  background-color: currentColor;
  -webkit-mask: var(--k-icon) center / contain no-repeat;
  mask: var(--k-icon) center / contain no-repeat;
}
"""


def build() -> str:
    parts = [HEADER]
    for svg in sorted(SRC.glob("*.svg")):
        data = " ".join(svg.read_text(encoding="utf-8").split())
        uri = "data:image/svg+xml," + quote(data, safe=" =:/\"<>,.-")
        uri = uri.replace('"', "'")
        parts.append(f'.k-icon--{svg.stem} {{ --k-icon: url("{uri}"); }}\n')
    return "".join(parts)


def main() -> int:
    css = build()
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != css:
            print("icons.css is out of date: run python tools/build_icons.py")
            return 1
        return 0
    OUT.write_text(css, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
